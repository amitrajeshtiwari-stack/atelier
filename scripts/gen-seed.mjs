/**
 * Generates supabase/seed.sql and lib/demo-posts.json from
 * scripts/demo-posts.source.mjs — one source of truth for sample prose.
 *
 *   node scripts/gen-seed.mjs
 *
 * NOTE: prose semicolons are rewritten to em dashes. The Supabase
 * dashboard SQL editor splits pasted scripts on `;` even inside string
 * literals, so seed files must not contain them.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { comments, login, posts, profile } from "./demo-posts.source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

/** Editor-proof prose: no semicolons, ever. */
const prose = (s) => s.replace(/;\s+/g, "— ").replace(/;$/, "—");

/* ── seed.sql ──────────────────────────────────────────────────────── */

const sqlArr = (tags) => `ARRAY[${tags.map((t) => `'${t}'`).join(", ")}]`;
const toSqlId = (userId) => `'${userId}'`;
const postIdBySlug = Object.fromEntries(posts.map((p) => [p.slug, p.id]));

// Dollar-quote markdown so apostrophes/backticks never need escaping.
const md = (text) => `$md$${prose(text)}$md$`;

const sql = `-- ═════════════════════════════════════════════════════════════════════
-- Atelier — seed.sql   (GENERATED by scripts/gen-seed.mjs — do not edit)
-- Run AFTER schema.sql. Creates the demo author (via auth.users —
-- Supabase flags this as a warning; expected on a fresh project),
-- then ${posts.length} published posts, sample comments and reactions.
-- Demo login: ${login.email} / ${login.password}
-- ═════════════════════════════════════════════════════════════════════

-- ── Demo author ──────────────────────────────────────────────────────
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password,
  email_confirmed_at, created_at, updated_at,
  raw_app_meta_data, raw_user_meta_data
) values (
  '00000000-0000-0000-0000-000000000000',
  ${toSqlId(profile.id)},
  'authenticated', 'authenticated',
  '${login.email}',
  crypt('${login.password}', gen_salt('bf')),
  now(), now(), now(),
  '{"provider":"email","providers":["email"]}',
  '${JSON.stringify({ username: profile.username, avatar_url: profile.avatar_url }).replaceAll("'", "''")}'
)
on conflict (id) do nothing;

insert into public.profiles (id, username, avatar_url, bio)
values (
  ${toSqlId(profile.id)},
  '${profile.username}',
  '${profile.avatar_url}',
  $md$${prose(profile.bio)}$md$
)
on conflict (id) do nothing;

-- ── Posts ────────────────────────────────────────────────────────────
insert into public.posts
  (id, author_id, slug, title, subtitle, excerpt, content_md, cover_image_url, category, tags, status, reading_time, published_at)
values
${posts
  .map(
    (p) => `(
  ${toSqlId(p.id)},
  ${toSqlId(p.author_id)},
  '${p.slug}',
  ${md(p.title)},
  ${p.subtitle ? md(p.subtitle) : "null"},
  ${md(p.excerpt)},
  ${md(p.content_md)},
  '${p.cover_image_url}',
  '${p.category}',
  ${sqlArr(p.tags)},
  'published', ${p.reading_time}, '${p.published_at}'
)`
  )
  .join(",\n")
  .replace(/^/, "")};

-- ── Sample comments ──────────────────────────────────────────────────
insert into public.comments (author_id, post_id, parent_id, body, created_at)
values
${comments
  .map(
    (c) => `(
  ${toSqlId(c.author_id)},
  '${postIdBySlug[c.post_slug]}',
  null,
  ${md(c.body)},
  '${c.created_at}'
)`
  )
  .join(",\n")};

-- ── Sample reactions (public counts) ─────────────────────────────────
insert into public.reactions (post_id, user_id, kind)
select p.id, ${toSqlId(profile.id)}, k.kind::public.reaction_kind
from public.posts p
cross join (values ('like'), ('insight')) as k(kind)
where p.status = 'published'
on conflict do nothing;
`;

writeFileSync(join(root, "supabase", "seed.sql"), sql);

/* ── lib/demo-posts.json ───────────────────────────────────────────── */

mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(
  join(root, "lib", "demo-posts.json"),
  // Minimal, zod-validated at import time in the app.
  JSON.stringify(
    {
      author: { ...profile, bio: prose(profile.bio) },
      posts: posts.map((p) => {
        const rest = {
          id: p.id,
          slug: p.slug,
          title: p.title,
          subtitle: p.subtitle,
          excerpt: p.excerpt,
          content_md: p.content_md,
          cover_image_url: p.cover_image_url,
          category: p.category,
          tags: p.tags,
          reading_time: p.reading_time,
          published_at: p.published_at,
        };
        return {
          ...rest,
          title: prose(rest.title),
          subtitle: rest.subtitle ? prose(rest.subtitle) : null,
          excerpt: prose(rest.excerpt),
          content_md: prose(rest.content_md),
        };
      }),
    },
    null,
    2
  ) + "\n"
);

console.log(
  `✓ regenerated supabase/seed.sql (${posts.length} posts) and lib/demo-posts.json`
);
